    private static File resolveSampleFile(String path) {
        File file = new File(path);
        return file.isAbsolute() ? file : new File(rootDir, path);
    }

    /**
     * Imports a PKCS#12 identity, applies an invisible signature, and verifies the saved PDF.
     *
     * <p>The PDF contains a standard signature form field and its Widget annotation.
     * A zero-width, zero-height rectangle makes the annotation invisible, as described
     * by the PDF specification for signature fields. The signature data is embedded
     * in the PDF and remains accessible through signature inspection and verification.
     * No visible signature text, image, or logo is drawn on the page.
     */
    private static void signInvisibleDigitalSignature() throws IOException {
        // Step 1: Read the PKCS#12 file generated earlier, or an existing configured identity.
        File certificateFile = resolveSampleFile(INVISIBLE_CERTIFICATE_PATH);
        if (!certificateFile.isFile() || !certificateFile.canRead()) {
            throw new IllegalStateException("Cannot read the invisible-signature PKCS#12 file");
        }
        if (!CPDFSignature.checkPKCS12Password(
                certificateFile.getAbsolutePath(), INVISIBLE_CERTIFICATE_PASSWORD)) {
            throw new IllegalStateException("Cannot unlock the invisible-signature PKCS#12 file");
        }
        CPDFX509 signingCertificate = CPDFSignature.getX509ByPKCS12Cert(
                certificateFile.getAbsolutePath(), INVISIBLE_CERTIFICATE_PASSWORD);
        if (signingCertificate == null || !signingCertificate.isValid()) {
            throw new IllegalStateException("Cannot import the invisible-signature certificate");
        }
        if (signingCertificate.isExpired()) {
            throw new IllegalStateException("The signing certificate is outside its validity period");
        }
        System.out.println("Invisible signature certificate imported: true");
        System.out.println("Invisible signature certificate subject: "
                + signingCertificate.getCertInfo().getSubject().getCommonName());

        // Step 2: Prepare the application's trust directory.
        File trustDirectory = resolveSampleFile(INVISIBLE_TRUST_DIRECTORY);
        Files.createDirectories(trustDirectory.toPath());
        String trustedPath = trustDirectory.getAbsolutePath() + File.separator;
        if (TRUST_INVISIBLE_DEMO_CERTIFICATE) {
            // Explicit test-only trust decision; this does not update Acrobat or the OS trust store.
            boolean added = signingCertificate.addToTrustedCertificates(
                    trustedPath, "invisible-demo.pem");
            if (!added) {
                throw new IllegalStateException("Cannot trust the generated demonstration certificate");
            }
            System.out.println("Invisible signature trust: generated test certificate explicitly trusted");
        }

        File output = new File(rootDir
                + "/out/SignatureTest/digitalSignature/Invisible_Signed.pdf");
        Files.createDirectories(output.getParentFile().toPath());
        CPDFDocument document = new CPDFDocument();
        try {
            // Step 3: Create a signature field with an invisible Widget annotation.
            document.open(rootDir + "/TestFiles/CommonFivePage.pdf");
            if (!document.isValid() || document.getPageCount() == 0) {
                throw new IllegalStateException("Cannot open the invisible-signature input PDF");
            }
            CPDFSignatureWidget widget = (CPDFSignatureWidget) document.pageAtIndex(0)
                    .addFormWidget(CPDFWidget.WidgetType.Widget_SignatureFields, document);
            if (widget == null || !widget.isValid()) {
                throw new IllegalStateException("Cannot create the invisible-signature field");
            }
            widget.setFieldName("InvisibleSignature");
            widget.setRect(new RectF(0, 0, 0, 0));

            // Step 4: Embed the signature; no visible appearance configuration is needed.
            boolean signed = document.writeSignature(
                    widget,
                    output.getAbsolutePath(),
                    certificateFile.getAbsolutePath(),
                    INVISIBLE_CERTIFICATE_PASSWORD,
                    "SG",
                    "Invisible digital signature",
                    CPDFDocument.PDFDocMdpP.PDFDocMdpPForbidAllModify);
            System.out.println("Invisible signature rect: [0, 0, 0, 0]");
            System.out.println("Invisible signature creation: " + signed);
            if (!signed) {
                throw new IllegalStateException("Invisible digital signature creation failed");
            }
        } finally {
            document.close();
        }

        // Step 5: Reopen the exact saved output and verify integrity, permissions, and trust.
        verifyInvisibleDigitalSignature(output, trustedPath);
    }

    private static void verifyInvisibleDigitalSignature(File output, String trustedPath) {
        CPDFDocument signedDocument = new CPDFDocument();
        try {
            signedDocument.open(output.getAbsolutePath());
            if (!signedDocument.isValid() || signedDocument.getSignatureCount() != 1) {
                throw new IllegalStateException("Cannot reopen the invisible signed PDF");
            }
            CPDFSignature signature = signedDocument.getPdfSignature(0);
            if (signature == null || !signature.isValid()) {
                throw new IllegalStateException("Cannot read the invisible signature");
            }
            CPDFSigner[] signers = signature.getSignerArr();
            if (signers == null || signers.length == 0) {
                throw new IllegalStateException("The invisible signature has no signer");
            }
            boolean integrity = signature.verify(signedDocument);
            boolean permissionsValid = signature.verifyDocument(signedDocument);
            boolean certificatesTrusted = true;
            boolean certificatesWithinValidity = true;
            for (int i = 0; i < signers.length; i++) {
                if (signers[i] == null || !signers[i].isValid()) {
                    throw new IllegalStateException("Cannot read the invisible-signature signer");
                }
                CPDFX509 certificate = signers[i].getCert();
                if (certificate == null || !certificate.isValid()) {
                    throw new IllegalStateException("Cannot read the invisible-signature signer certificate");
                }
                boolean withinValidity = !certificate.isExpired();
                boolean chainTrusted = certificate.verifyGetChain(trustedPath, signature);
                certificatesWithinValidity &= withinValidity;
                certificatesTrusted &= chainTrusted;
                System.out.println("Invisible signature signer " + i
                        + " certificate within validity period: " + withinValidity);
                System.out.println("Invisible signature signer " + i
                        + " certificate chain trusted: " + chainTrusted);
            }
            boolean verified = integrity
                    && permissionsValid
                    && certificatesWithinValidity
                    && certificatesTrusted;
            System.out.println("Invisible signature verification: " + integrity);
            System.out.println("Invisible signature document permissions valid: " + permissionsValid);
            System.out.println("Invisible signature basic verification passed: " + verified);
            System.out.println("Invisible signature revocation/LTV checks: not performed");
            System.out.println("Invisible signed PDF: " + output.getAbsolutePath());
            if (!verified) {
                throw new IllegalStateException("Invisible signature verification failed");
            }
        } finally {
            signedDocument.close();
        }
    }

    private static void readDigitalSignatureInformation(CPDFDocument document){
        for (int i = 0; i < document.getSignatureCount(); i++) {
            CPDFSignature signature = document.getPdfSignature(i);
            // Check if the signer array exists and is not empty
            if (signature.getSignerArr() != null && signature.getSignerArr().length > 0) {
                CPDFSigner signer = signature.getSignerArr()[0];
                CPDFOwnerInfo subject = signer.getCert().getCertInfo().getSubject();
                System.out.println("Name: " + signature.getName());
                System.out.println("Location: " + signature.getLocation());
                System.out.println("Reason: " + signature.getReason());
                System.out.println("Date: " + signature.getDate());
                System.out.println("Subject: " + subject.toString());
            }
        }
    }

    /**
     * Verify whether the specified certificate file is trusted.
     *
     * To verify the trustworthiness of a certificate, you need to validate that all certificates in the certificate chain are trustworthy.
     *
     */
    private static void verifyDigitalCertificates(){
        String certFilePath = rootDir+"/out/SignatureTest/certificate/Certificate.pfx";
        String password = "ComPDFKit";
        if (CPDFSignature.checkPKCS12Password(certFilePath, password)) {
            CPDFX509 x509 = CPDFSignature.getX509ByPKCS12Cert(certFilePath, password);
            boolean isTrusted = x509.checkCertificateIsTrusted(rootDir + "/SignatureTest/trusted");
            if (isTrusted) {
                // Certificate is trusted.
                System.out.println("certificate is in trusted list");
            } else {
                // Certificate is trusted.
                System.out.println("not in");
            }
        }
    }

    private static void verifyDigitalSignatures(CPDFDocument document){
        // Iterate through all digital signatures.
        for (int i = 0; i < document.getSignatureCount(); i++) {
            CPDFSignature signature = document.getPdfSignature(i);
            // Check if the signer array exists and is not empty.
            if (signature.getSignerArr() != null && signature.getSignerArr().length > 0) {
                CPDFSigner signer = signature.getSignerArr()[0];

                // Verify the validity of the signature.
                boolean verifyValid = signature.verify(document);

                // Verify if the document has not been modified.
                boolean unmodified = signature.verifyDocument(document);

                // Determine if the signature is valid and the document is unmodified.
                boolean isSignVerified = verifyValid && unmodified;

                // Check if the certificate is trusted.
                boolean certChainTrusted = signer.getCert().verifyGetChain(rootDir+"/out/SignatureTest/certificate/", signature);
                boolean certificateIsTrusted = signer.getCert().checkCertificateIsTrusted(rootDir + "/SignatureTest/trusted");
                boolean certIsTrusted = certChainTrusted || certificateIsTrusted;

                // Check if the certificate has expired.
                boolean isExpired = signer.getCert().isExpired();
                if (isExpired) {
                    System.out.println("the certificate is expired.");
                }else {
                    System.out.println("the certificate not expired.");
                }

                // Take appropriate actions based on the verification results.
                if (isSignVerified && certIsTrusted) {
                    // Signature is valid and the certificate is trusted.
                    // Perform the corresponding actions.
                    System.out.println("Signature is valid and the certificate is trusted.");
                    System.out.println("Perform the corresponding actions.");
                } else if (isSignVerified && !certIsTrusted) {
                    // Signature is valid but the certificate is not trusted.
                    // Perform the corresponding actions.
                    System.out.println("Signature is valid but the certificate is not trusted.");
                    System.out.println("Perform the corresponding actions.");
                } else {
                    // Signature is invalid.
                    // Perform the corresponding actions.
                    System.out.println("Signature is invalid.");
                    System.out.println("Perform the corresponding actions.");
                }
            }
        }
    }

    private static void trustCertificate(CPDFDocument document){
        // Add the certificate in the local storage as a trusted certificate.
        String certFilePath = rootDir+"/out/SignatureTest/certificate/Certificate.pfx";
        String password = "ComPDFKit";
        if (CPDFSignature.checkPKCS12Password(certFilePath, password)) {
            CPDFX509 x509 = CPDFSignature.getX509ByPKCS12Cert(certFilePath, password);
            // Add your certificate to the trust path.
            boolean result = x509.addToTrustedCertificates(rootDir + "/SignatureTest/trusted","compdfkit.pem");
            if (result) {
                System.out.println("add to trusted certificates success");
            }else {
                System.out.println("add to trusted certificates fail");
            }
        }
        // Add digital signature certificate in pdf file as trusted certificate.
        CPDFSignature signature = document.getPdfSignature(0);
        CPDFSigner signer = signature.getSignerArr()[0];
        CPDFX509 cpdfx509 = signer.getCert();

        boolean result = cpdfx509.addToTrustedCertificates(rootDir + "/SignatureTest/trusted","compdfkit.pem");
        if (result) {
            System.out.println("add to trusted certificates success");
        }else {
            System.out.println("add to trusted certificates fail");
        }
    }

    private static void removeDigitalSignatures(CPDFDocument document){
        // Remove digital signature.
        // You can choose if you want to remove the appearance.
        for (int i = 0; i < document.getSignatureCount(); i++) {
            CPDFSignature signature = document.getPdfSignature(i);
            if (i == 0){
                // Remove first digital signature.
                boolean result = document.removeSignature(signature, document, true);
                if (result) {
                    System.out.println("remove signature success");
                }else {
                    System.out.println("remove signature fail");
                }
            }
        }
        document.save(rootDir + "/out/SignatureTest/signatureRemoveTest.pdf", CPDFDocument.PDFDocumentSaveType.PDFDocumentSaveNoIncremental);
    }

